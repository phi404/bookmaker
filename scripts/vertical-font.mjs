import { readFile, writeFile } from 'node:fs/promises';
import { create } from 'fontkit';
import { absolute, hash } from './lib.mjs';

// Generate only the bundled font's vertical alternates. No runtime font parser.
export async function verticalFontSource() {
  const bytes=await readFile(absolute('public/fonts/NotoSerifJP-Regular.otf')),font=create(bytes);
  const unicode=await readFile(absolute('fixtures/unicode/VerticalOrientation-17.0.0.txt'),'utf8'),properties=[];
  for(const line of unicode.split('\n')){const m=line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(U|R|Tu|Tr)\b/u);if(m)properties.push([parseInt(m[1],16),parseInt(m[2]??m[1],16),m[3]]);}
  const ranges=[];for(const [start,end] of properties.filter(row=>['U','Tu'].includes(row[2]))){const previous=ranges.at(-1);if(previous&&previous[1]+1===start)previous[1]=end;else ranges.push([start,end]);}
  const transforms=new Set();for(const [start,end,property] of properties)if(['Tu','Tr'].includes(property))for(let cp=start;cp<=end;cp++)transforms.add(cp);
  const tables=new Map();for(let i=0;i<bytes.readUInt16BE(4);i++){const at=12+i*16;tables.set(bytes.toString('ascii',at,at+4),bytes.readUInt32BE(at+8));}
  const vorg=tables.get('VORG');if(vorg===undefined)throw Error('Bundled CFF font requires VORG');
  const origin=bytes.readInt16BE(vorg+4),metrics=new Map();for(let i=0;i<bytes.readUInt16BE(vorg+6);i++)metrics.set(bytes.readUInt16BE(vorg+8+i*4),bytes.readInt16BE(vorg+10+i*4));
  const glyphs={},origins={};
  for(const cp of font.characterSet){const char=String.fromCodePoint(cp),glyph=font.glyphForCodePoint(cp);if(metrics.has(glyph.id))origins[char]=metrics.get(glyph.id);
    const alt=font.layout(char,['vert']).glyphs;if(alt.length!==1){if(transforms.has(cp))throw Error('Unexpected vertical substitution');continue;}if(alt[0].id===glyph.id)continue;
    glyphs[char]=[alt[0].path.toSVG(),metrics.get(alt[0].id)??origin];
  }
  if(!glyphs['「']||!glyphs['、']||!glyphs['ぁ']||!glyphs['ー'])throw Error('Missing Japanese vertical alternates');
  return '/** Generated by scripts/vertical-font.mjs from Noto Serif JP (OFL) and Unicode 17 (Unicode-3.0). */\n'+
    'export const VERTICAL_FONT_SHA256 = '+JSON.stringify(hash(bytes))+';\n'+
    'export const VERTICAL_UNICODE_SHA256 = '+JSON.stringify(hash(unicode))+';\n'+
    'export const FONT_UNITS_PER_EM = '+font.unitsPerEm+';\nexport const FONT_VERTICAL_ORIGIN = '+origin+';\n'+
    'export const UPRIGHT_RANGES: readonly (readonly [number, number])[] = '+JSON.stringify(ranges)+';\n'+
    'export const VERTICAL_ORIGINS: Readonly<Record<string, number>> = '+JSON.stringify(origins)+';\n'+
    'export const VERTICAL_GLYPHS: Readonly<Record<string, readonly [string, number]>> = '+JSON.stringify(glyphs,null,2)+';\n';
}
const source=await verticalFontSource(),target=absolute('src/render/vertical-font.ts');
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==source)throw Error('Vertical font data is stale');console.log('Vertical font data matches bundled font and Unicode 17.');}
else{await writeFile(target,source);console.log('Generated vertical glyphs and metrics.');}
